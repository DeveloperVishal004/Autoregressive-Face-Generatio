class CelebAVQVAE(nn.Module):
    def __init__(self, latent_dim=256, num_embeddings=512):
        super().__init__()

        # [RESTORED FIX] Explicitly use keyword arguments!
        self.encoder = CelebAEncoder(latent_dim=latent_dim)
        self.vq_layer = VectorQuantizerEMA(num_embeddings, latent_dim, commitment_cost=0.25)
        self.decoder = CelebADecoder(latent_dim=latent_dim)

    def forward(self, x):
        z = self.encoder(x)
        quantized, vq_loss, encodings = self.vq_layer(z)
        x_recon = self.decoder(quantized)
        return x_recon, vq_loss, encodings

