import torch
import torch.nn as nn
import torch.nn.functional as F

class VectorQuantizerEMA(nn.Module):
    def __init__(self, num_embeddings, embedding_dim, commitment_cost=0.25, decay=0.99, epsilon=1e-5):
        super().__init__()
        self.num_embeddings = num_embeddings
        self.embedding_dim = embedding_dim
        self.commitment_cost = commitment_cost

        # EMA specific parameters
        self.decay = decay
        self.epsilon = epsilon

        # Initialize embeddings
        self.embedding = nn.Embedding(num_embeddings, embedding_dim)
        self.embedding.weight.data.uniform_(-1/num_embeddings, 1/num_embeddings)

        # Buffers for EMA (these update during forward passes but don't use Adam)
        self.register_buffer("ema_cluster_size", torch.zeros(num_embeddings))
        self.register_buffer("ema_w", self.embedding.weight.data.clone())

    def forward(self, x):
        # Flatten input
        flat_x = x.permute(0, 2, 3, 1).contiguous().view(-1, self.embedding_dim)

        # Calculate distances
        distances = (torch.sum(flat_x**2, dim=1, keepdim=True)
                     + torch.sum(self.embedding.weight**2, dim=1)
                     - 2 * torch.matmul(flat_x, self.embedding.weight.t()))

        # Find closest encodings
        encoding_indices = torch.argmin(distances, dim=1)

        # [RESTORED FIX] View as [Batch, Height, Width, Channels] first, THEN permute to [Batch, Channels, Height, Width]
        quantized = self.embedding(encoding_indices).view(x.shape[0], x.shape[2], x.shape[3], self.embedding_dim)
        quantized = quantized.permute(0, 3, 1, 2).contiguous()

        # EMA Updates (Only during training!)
        if self.training:
            encodings = F.one_hot(encoding_indices, self.num_embeddings).float()

            # Update cluster sizes
            n = torch.sum(encodings, dim=0)
            self.ema_cluster_size = self.ema_cluster_size * self.decay + n * (1 - self.decay)

            # Laplace smoothing
            n_sum = torch.sum(self.ema_cluster_size)
            self.ema_cluster_size = ((self.ema_cluster_size + self.epsilon) /
                                     (n_sum + self.num_embeddings * self.epsilon) * n_sum)

            # Update weights
            dw = torch.matmul(encodings.t(), flat_x)
            self.ema_w = self.ema_w * self.decay + dw * (1 - self.decay)
            self.embedding.weight.data = self.ema_w / self.ema_cluster_size.unsqueeze(1)

        # The Commitment Loss
        e_latent_loss = F.mse_loss(quantized.detach(), x)
        commitment_loss = self.commitment_cost * e_latent_loss

        # Straight-through estimator
        quantized = x + (quantized - x).detach()

        return quantized, commitment_loss, encoding_indices.view(x.shape[0], x.shape[2], x.shape[3])

