class CelebAEncoder(nn.Module):
    def __init__(self, in_channels=3, latent_dim=256):
        super().__init__()
        self.conv1 = nn.Sequential(
            nn.Conv2d(in_channels, 64, kernel_size=4, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(64),
            nn.LeakyReLU(0.2)
        )
        self.conv2 = nn.Sequential(
            nn.Conv2d(64, 128, kernel_size=4, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(128),
            nn.LeakyReLU(0.2)
        )
        self.conv3 = nn.Sequential(
            nn.Conv2d(128, latent_dim, kernel_size=4, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(latent_dim)
        )

    def forward(self, x, debug=False):
        if debug: print(f"Encoder Input: {x.shape}")
        x = self.conv1(x)
        if debug: print(f"After Conv1:   {x.shape}")
        x = self.conv2(x)
        if debug: print(f"After Conv2:   {x.shape}")
        x = self.conv3(x)
        if debug: print(f"After Conv3:   {x.shape}")
        return x

class CelebADecoder(nn.Module):
    def __init__(self, out_channels=3, latent_dim=256):
        super().__init__()
        self.deconv1 = nn.Sequential(
            nn.ConvTranspose2d(latent_dim, 128, kernel_size=4, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(128),
            nn.ReLU()
        )
        self.deconv2 = nn.Sequential(
            nn.ConvTranspose2d(128, 64, kernel_size=4, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(64),
            nn.ReLU()
        )
        self.deconv3 = nn.Sequential(
            nn.ConvTranspose2d(64, out_channels, kernel_size=4, stride=2, padding=1),
            nn.Tanh() # Output range perfectly matches [-1, 1]
        )

    def forward(self, x, debug=False):
        if debug: print(f"\nDecoder Input: {x.shape}")
        x = self.deconv1(x)
        if debug: print(f"After Deconv1: {x.shape}")
        x = self.deconv2(x)
        if debug: print(f"After Deconv2: {x.shape}")
        x = self.deconv3(x)
        if debug: print(f"After Deconv3: {x.shape}")
        return x

