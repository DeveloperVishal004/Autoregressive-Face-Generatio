gpt_epochs = 10
gpt_lr = 3e-4

optimizer = optim.Adam(gpt_model.parameters(), lr=gpt_lr)
criterion = nn.CrossEntropyLoss()

# 1. Bring back the GradScaler for memory efficiency!
scaler = torch.amp.GradScaler('cuda')

gpt_model.train()
print("🚀 Starting Mini-GPT Training...")

for epoch in range(gpt_epochs):
    total_loss = 0

    for batch_idx, (x, y) in enumerate(dataloader):
        x, y = x.to(device), y.to(device)

        optimizer.zero_grad(set_to_none=True)

        # 2. Mixed Precision Context
        with torch.autocast(device_type='cuda', dtype=torch.float16):
            logits = gpt_model(x)

            # Your perfect reshaping logic:
            loss = criterion(logits.view(-1, 513), y.view(-1))

        # Backward pass
        scaler.scale(loss).backward()

        # 3. Transformer Safety Net: Unscale and Clip Gradients
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(gpt_model.parameters(), max_norm=1.0)

        # Optimizer step
        scaler.step(optimizer)
        scaler.update()

        total_loss += loss.item()

    avg_loss = total_loss / len(dataloader)
    print(f"Epoch [{epoch+1}/{gpt_epochs}] | GPT Loss: {avg_loss:.4f}")

print("🎉 GPT Training Complete!")

