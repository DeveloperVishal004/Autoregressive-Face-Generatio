class LatentSequenceDataset(Dataset):
    def __init__(self, npy_path, codebook_size=512):
        print(f"Loading data from {npy_path}...")
        # Load the [202599, 8, 8] array
        self.data = np.load(npy_path).astype(np.int64)

        # Flatten the 8x8 grids into 1D sequences of length 64
        self.data = self.data.reshape(self.data.shape[0], 64)

        self.sos_token = codebook_size # Token 512

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        sequence = self.data[idx]

        # Input: [SOS, t1, t2, ... t63]
        x = np.concatenate(([self.sos_token], sequence[:-1]))

        # Target: [t1, t2, t3, ... t64]
        y = sequence

        return torch.tensor(x, dtype=torch.long), torch.tensor(y, dtype=torch.long)

# ==========================================
# 2. The Mini-GPT Architecture
# ==========================================
class MiniGPT(nn.Module):
    def __init__(self, vocab_size=513, seq_len=64, embed_dim=256, num_heads=8, num_layers=6):
        super().__init__()

        # Token Embeddings (Vocab 0-511 + SOS token 512)
        self.token_emb = nn.Embedding(vocab_size, embed_dim)

        # Positional Embeddings (Tells the model WHERE the token is in the 8x8 grid)
        self.pos_emb = nn.Embedding(seq_len, embed_dim)

        # The Transformer Blocks
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=embed_dim,
            nhead=num_heads,
            dim_feedforward=embed_dim * 4,
            dropout=0.1,
            batch_first=True
        )
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)

        # Final output layer to predict the next token probability
        self.to_logits = nn.Linear(embed_dim, vocab_size)

    def forward(self, x):
        batch_size, seq_length = x.shape
        device = x.device

        # 1. Create position indices [0, 1, 2... 63]
        positions = torch.arange(0, seq_length, dtype=torch.long, device=device).unsqueeze(0).expand(batch_size, seq_length)

        # 2. Add Token + Positional embeddings
        embeddings = self.token_emb(x) + self.pos_emb(positions)

        # 3. Create a Causal Mask (Ensures token N cannot look ahead at token N+1)
        causal_mask = nn.Transformer.generate_square_subsequent_mask(seq_length, device=device)

        # 4. Pass through Transformer
        hidden_states = self.transformer(embeddings, mask=causal_mask, is_causal=True)

        # 5. Predict the next tokens
        logits = self.to_logits(hidden_states)
        return logits

