seq_len = 64
sos_token = 512

print("🧠 Imagining new faces token by token...")

# 2. Start with a batch of SOS tokens
generated_sequence = torch.full((num_samples, 1), sos_token, dtype=torch.long, device=device)

with torch.no_grad():
    # 3. Autoregressive Loop: Generate 64 tokens one by one
    for i in range(seq_len):
        logits = gpt_model(generated_sequence)

        # We only care about the prediction for the LAST token
        next_token_logits = logits[:, -1, :]

        # Temperature sampling
        probs = F.softmax(next_token_logits / 1.0, dim=-1)

        # Force the model to NEVER sample the SOS token again
        probs[:, sos_token] = 0.0
        probs = probs / probs.sum(dim=-1, keepdim=True)

        # Sample the next token
        next_token = torch.multinomial(probs, num_samples=1)
        generated_sequence = torch.cat((generated_sequence, next_token), dim=1)

# 4. Remove SOS token and reshape to 8x8 latent grid
latent_indices = generated_sequence[:, 1:].reshape(num_samples, 8, 8)

# 5. Map the integer indices back to continuous 256-D Codebook vectors (OPTIMIZED)
# Passing [16, 8, 8] directly into the embedding returns [16, 8, 8, 256] instantly
quantized = base_vq_model.vq_layer.embedding(latent_indices)

# Permute to [Batch, Channels, Height, Width] for the convolutional decoder
quantized = quantized.permute(0, 3, 1, 2).contiguous()

# 6. Final Render: Decode latents into RGB pixels
fake_faces = base_vq_model.decoder(quantized)

